package com.example.agentdemo.agent;

/**
 * 两条路径（手写 ReAct / 框架原生）共用的"行为约束"。
 *
 * 为什么单独抽出来：最初我只把手写版的约束写进了 {@link ReActAgent#systemPrompt()}，
 * 框架版的 prompt 里什么都没有。结果同一个问题（"公司裁员会赔几个月工资？"）
 * 两边答案不一样——手写版直接说"资料中没有相关信息"，框架版补了一段《劳动合同法》的 N+1。
 * 一开始差点当成"模型随机性"，查下来发现是**两套不同的指令**，属于实验设计错误：
 * 比较两个 Agent 却给它们不同的规矩，结论不成立。
 *
 * 所以：协议格式（Thought/Action 怎么写）各管各的，行为约束（什么能说什么不能说）必须共用这一份。
 */
final class AgentPrompts {

    private AgentPrompts() {
    }

    /**
     * 行为约束。第 5、7 条是这轮实测逼出来的，不是照着别人的 prompt 抄的：
     *   - 第 5 条：RAG 接上以后，模型明明检索到了无关片段，还会顺着"公司规定"的口气编。
     *   - 第 7 条：Q4 实测发现，直接说"资料里没有"对用户价值有限；但模型一旦开始补充法律常识，
     *     就很容易和"公司规定"混在一起说。折中办法是允许补充，但必须显式标注来源不同。
     */
    static String behaviorRules() {
        return """
                行为约束：
                1. 涉及公司制度、政策、福利、流程的问题，必须先查知识库（工具清单里的检索工具），
                   **只依据检索回来的片段回答**；片段里没有就直说"资料中没有相关信息"。
                2. 不要凭空编造公司制度里的细节（天数、金额、期限、审批层级）。片段里没写的数字，
                   一律不许自己补。
                3. 如果你要补充公司资料之外的通用常识或法律条款，必须**显式标注"这不是公司规定"**，
                   让用户能分清哪句话来自资料、哪句话不是（资料归资料，常识归常识，不许混着说）。
                4. 工具报错或服务不可用时，如实告诉用户哪一步失败了，不要绕过去硬答。
                """;
    }
}
